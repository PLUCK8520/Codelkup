package com.codelkup.module.ai.client;

/**
 * AI 客户端抽象（M3-4 / ADR-1）。
 *
 * <h2>为什么先抽接口</h2>
 * 业务层（相似问题 / TL;DR / RAG 问答）只依赖这个接口，不关心背后是 DeepSeek、
 * 还是将来换成 Spring AI 或别的供应商 —— ADR-1 留它就是留这个替换点：
 * 换实现时业务层一行不动。
 *
 * <h2>两条契约（调用方必须知道）</h2>
 * <ol>
 *   <li><b>永不抛异常</b>：不可用（没配 key / 总开关关闭）、超时、上游报错、
 *       返回为空 —— 一律以 {@link AiReply#degraded} 的形态返回。
 *       AI 是"锦上添花"的能力，任何失败都不该把调用方的业务流程打断
 *       （与限流/计数"依赖故障时降级放行"是同一口径）。</li>
 *   <li><b>不重试</b>：一次调用就是一次；要重试由调用方决定。
 *       自动重试在这里等于"偷偷翻倍成本"，而成本正是本模块最需要盯住的量。</li>
 * </ol>
 *
 * @author 刘
 */
public interface AiClient {

    /**
     * 当前是否具备调用条件（总开关打开且配置了 key）。
     *
     * <p>调用方可以用它提前短路（比如直接返回"仅检索结果 + 未启用提示"），
     * 省掉一次注定降级的调用。注意这是<b>配置态</b>而非"上游此刻健康"——
     * 上游是否可用只能通过一次真实调用知道。
     */
    boolean available();

    /** 发起一次对话补全；失败返回降级结果，不抛异常 */
    AiReply chat(AiChatRequest request);
}