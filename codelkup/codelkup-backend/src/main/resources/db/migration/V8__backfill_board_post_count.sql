-- ============================================================
-- 回填 t_board.post_count（冗余计数列）
--
-- 为什么需要这次回填：
--   post_count 是"读多写少"的反范式计数列，只在**业务代码路径**上维护
--   （PostServiceImpl 创建 +1 / 换板块 -1+1 / 删除 -1，见 BoardMapper.addPostCount）。
--   而历史数据（种子脚本直接 INSERT t_post）从来没有走这些路径，
--   于是计数停在建表时的初值：实测综合讨论 81、后端 35，其余 8 个板块全 0，
--   合计 116 —— 而 t_post 里 status=1 的真实行数是 10116。
--
-- 为什么现在修：
--   V0.4 新增了 /boards 板块总览页，它会把每个板块的计数摆在卡片正面上，
--   点进去的列表页又显示真实条数（1090），两个数字同屏互相打脸。
--   计数不准以前只影响首页右栏那一列小字，现在成了主要信息。
--
-- 口径：与 addPostCount 的调用点一致 —— 只统计 status=1（已发布）。
--   博客/待审(0)、已删(2)、封禁(3) 都不计入，和"删帖时 -1"的语义对齐。
--
-- 幂等：这是一次全量重算（SET = COUNT），重复执行结果相同。
-- ============================================================

UPDATE t_board b
SET b.post_count = (SELECT COUNT(*)
                    FROM t_post p
                    WHERE p.board_id = b.id
                      AND p.status = 1);
